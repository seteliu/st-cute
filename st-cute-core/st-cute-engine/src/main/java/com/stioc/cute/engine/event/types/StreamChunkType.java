package com.stioc.cute.engine.event.types;

/**
 * 流式切片语义类型：区分「常规增量内容」与「流控制信号」。
 * <p>
 * 承载于 {@link StreamChunkPayload#getType()}，缺省为 {@code null} 表示常规增量内容；
 * 为 null 时序列化不写出该字段，故常规 chunk 的报文与引入本字段之前逐字节一致，零开销。
 * </p>
 */
public enum StreamChunkType {

    /**
     * 清空信号：要求下游丢弃该 messageId 已累积的流式内容，从零开始重新累积。
     * <p>
     * 触发场景为<b>透明重试</b>——流在已产出部分内容后失败时，重试会从头发送完整内容，
     * 下游若继续累加会让失败前已推送的片段重复一遍。本信号在重放的首片内容<b>之前</b>发出，
     * 下游只需「收到即清空」，无需自行识别重试边界与判断是否已产出内容。
     * </p>
     * <p>
     * 本信号不携带文本，只作用于自身的流（思考流清空只清思考缓存，正文流清空只清正文缓存），
     * 故重试时会成对发出两条。
     * </p>
     */
    CLEAR
}
