package com.stioc.cute.engine.tool.types;

/**
 * 工具访问等级（读/写/敏感三档）。
 * <p>
 * 统一承载原 isReadOnly / isWriteTool 双布尔的治理语义，供引擎并发调度与宿主权限矩阵共同消费：
 * <ul>
 *   <li>{@link #READ}：只读无外部副作用，支持并发批执行，权限矩阵全模式放行</li>
 *   <li>{@link #WRITE}：产生外部持久化写副作用，执行期参与写锁排他；
 *   只读权限模式下需人工审批，智能审批模式下直接放行</li>
 *   <li>{@link #SENSITIVE}：敏感级高危操作（如删除文件、执行终端命令），
 *   除全部放行模式外一律进入人在回路审批（智能审批模式不放行）</li>
 * </ul>
 * 未显式声明访问等级的工具默认按 {@link #SENSITIVE} 兜底（宁严勿漏，如 MCP 外部工具）。
 * </p>
 */
public enum ToolAccessLevel {

    /**
     * 只读：无外部副作用，支持并发执行，权限矩阵全模式放行
     */
    READ,

    /**
     * 写：产生外部持久化写副作用，执行期参与写锁排他；
     * 只读模式需人工审批，智能审批模式直接放行
     */
    WRITE,

    /**
     * 敏感：高危操作（删除文件、执行终端命令等），智能审批模式不放行，
     * 除全部放行模式外一律进入人在回路审批
     */
    SENSITIVE
}
